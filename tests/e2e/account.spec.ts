import { test, expect } from '@playwright/test';
test('register, verify delivered code, sign in, and sign out', async ({page,request}) => {
 const email=`browser-${Date.now()}@example.test`;
 await page.goto('/register');
 await page.getByLabel('Full name as on ID').fill('Maria Browser');
 await page.getByLabel('Philippine mobile').fill('+63 912 345 6789');
 await page.getByLabel('Email address').fill(email);
 await page.getByLabel('Password',{exact:true}).fill('Browser123');
 await page.getByLabel('Confirm password').fill('Browser123');
 await page.getByRole('checkbox').check();
 await page.getByRole('button',{name:'Create account',exact:true}).click();
 await expect(page).toHaveURL(/verify-email/);
 const inbox=await (await request.get('http://127.0.0.1:8025/api/v1/messages')).json();
 const message=inbox.messages.find((m:{To:{Address:string}[]})=>m.To.some(t=>t.Address===email));
 expect(message).toBeTruthy();
 const content=await (await request.get(`http://127.0.0.1:8025/api/v1/message/${message.ID}`)).json();
 const code=content.Text.match(/\b\d{6}\b/)[0];
 await page.getByLabel('Verification code').fill(code);
 await page.getByRole('button',{name:'Verify email',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('Email verified');
 await page.goto('/sign-in');
 await page.getByLabel('Email address').fill(email);
 await page.getByLabel('Password',{exact:true}).fill('Browser123');
 await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await expect(page).toHaveURL(/account/);
 await expect(page.getByText('Email verified. Your account is ready for booking.')).toBeVisible();
 await page.screenshot({path:'/tmp/macapagal-account.png',fullPage:true});
 await page.getByRole('button',{name:'Sign out',exact:true}).click();
 await expect(page).toHaveURL(/sign-in/);
});
